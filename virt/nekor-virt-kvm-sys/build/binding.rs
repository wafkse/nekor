use std::{env, fs, path::PathBuf};

mod adapt;

/// Generate the default and processed binding files for the selected Linux pin and target.
///
/// The build environment selects the kernel pin, target, and exported header directory.
///
/// # Failure
///
/// Returns an error for missing or invalid environment settings, parsing failures,
/// or failed filesystem operations.
pub fn generate() -> Result<(), Box<dyn core::error::Error>> {
    let kernel_channel = env::var("NEKOR_KVM_CHANNEL")?;

    if !matches!(kernel_channel.as_str(), "lts" | "stable") {
        return Err("NEKOR_KVM_CHANNEL must be lts or stable".into());
    }

    let kernel_tag = env::var("NEKOR_KVM_TAG")?;
    let kernel_commit = env::var("NEKOR_KVM_COMMIT")?;
    let crate_version = env::var("CARGO_PKG_VERSION")?;
    let target_triple = env::var("NEKOR_KVM_TARGET")?;
    let kernel_include_directory = PathBuf::from("checkout/header")
        .join(&target_triple)
        .join(&kernel_channel)
        .join("include");
    let target_output_directory = PathBuf::from(env::var("OUT_DIR")?).join(&target_triple);
    let wrapper_header_path = target_output_directory.join("kvm-wrapper.h");

    fs::create_dir_all(&target_output_directory)?;
    fs::write(&wrapper_header_path, include_str!("kvm-wrapper.h"))?;

    println!("cargo:rerun-if-changed={}", kernel_include_directory.display());

    let default_binding = bindgen::Builder::default()
        .header(wrapper_header_path.to_string_lossy())
        .clang_macro_fallback()
        .clang_macro_fallback_build_dir(&target_output_directory)
        .clang_arg(format!("--target={target_triple}"))
        .clang_arg("-nostdinc")
        .clang_arg(format!("-I{}", kernel_include_directory.display()))
        .allowlist_type("kvm_.*")
        .allowlist_var("KVM_.*")
        .use_core()
        .rust_edition(bindgen::RustEdition::Edition2024)
        .wrap_unsafe_ops(true)
        .generate_comments(true)
        .layout_tests(true)
        .derive_debug(false)
        .formatter(bindgen::Formatter::None)
        .generate()?;
    let default_binding_ast = syn::parse_file(&default_binding.to_string())?;
    let processed_binding_ast = adapt::Adapter::new(&default_binding_ast).apply();
    let processed_binding_source = prettyplease::unparse(&processed_binding_ast);
    let default_binding_source = prettyplease::unparse(&default_binding_ast);
    let clang_version = bindgen::clang_version().full;
    let generation_metadata = format!(
        "// SPDX-License-Identifier: GPL-2.0 WITH Linux-syscall-note
//
// Generated by build/binding.rs. Do not edit.
//
// - Linux tag: {kernel_tag}
// - Linux commit: {kernel_commit}
// - Repository: https://github.com/gregkh/linux.git
// - Target: {target_triple}
// - Crate version: {crate_version}
//
// - Generator: bindgen and prettyplease
// - Compiler: {clang_version}
// - Rust edition: 2024
// - Dependency lockfile: Cargo.lock
//
// UAPI licensing follows the source headers and Linux-syscall-note exception.

"
    );
    let channel_output_directory = target_output_directory.join(&kernel_channel);

    fs::create_dir_all(&channel_output_directory)?;
    fs::write(
        channel_output_directory.join("binding-processed.rs"),
        generation_metadata.clone() + &processed_binding_source,
    )?;
    fs::write(
        channel_output_directory.join("binding-default.rs"),
        generation_metadata + &default_binding_source,
    )?;

    Ok(())
}
