use std::{env, fs, path::PathBuf};

/// Generate the requested raw UAPI into Cargo's output directory.
pub fn generate() -> Result<(), Box<dyn core::error::Error>> {
    let channel = env::var("NEKOR_KVM_CHANNEL")?;

    if !matches!(channel.as_str(), "lts" | "stable") {
        return Err("NEKOR_KVM_CHANNEL must be lts or stable".into());
    }

    let tag = env::var("NEKOR_KVM_TAG")?;
    let commit = env::var("NEKOR_KVM_COMMIT")?;
    let version = env::var("CARGO_PKG_VERSION")?;
    let target = env::var("NEKOR_KVM_TARGET")?;
    let include = PathBuf::from("checkout/header")
        .join(&target)
        .join(&channel)
        .join("include");
    let output = PathBuf::from(env::var("OUT_DIR")?).join(&target);
    let wrapper = output.join("kvm-wrapper.h");

    fs::create_dir_all(&output)?;
    fs::write(&wrapper, include_str!("kvm-wrapper.h"))?;

    println!("cargo:rerun-if-changed={}", include.display());

    let binding = bindgen::Builder::default()
        .header(wrapper.to_string_lossy())
        .clang_macro_fallback()
        .clang_macro_fallback_build_dir(&output)
        .clang_arg(format!("--target={target}"))
        .clang_arg("-nostdinc")
        .clang_arg(format!("-I{}", include.display()))
        .allowlist_type("kvm_.*")
        .allowlist_var("KVM_.*")
        .use_core()
        .rust_edition(bindgen::RustEdition::Edition2024)
        .wrap_unsafe_ops(true)
        .generate_comments(true)
        .layout_tests(false)
        .derive_debug(false)
        .formatter(bindgen::Formatter::None)
        .generate()?;
    let syntax = syn::parse_file(&binding.to_string())?;

    let source = prettyplease::unparse(&syntax);
    let clang = bindgen::clang_version().full;
    let metadata = format!(
        "// SPDX-License-Identifier: GPL-2.0 WITH Linux-syscall-note
//
// Generated by build/binding.rs. Do not edit.
//
// - Linux tag: {tag}
// - Linux commit: {commit}
// - Repository: https://github.com/gregkh/linux.git
// - Target: {target}
// - Crate version: {version}
//
// - Generator: bindgen and prettyplease
// - Compiler: {clang}
// - Rust edition: 2024
// - Dependency lockfile: Cargo.lock
//
// UAPI licensing follows the source headers and Linux-syscall-note exception.

"
    );
    let output = output.join(format!("{channel}.rs"));

    fs::write(output, metadata + &source)?;

    Ok(())
}
